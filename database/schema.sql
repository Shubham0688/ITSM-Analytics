CREATE TABLE departments (
    department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE agents (
    agent_id VARCHAR2(20) PRIMARY KEY
);

CREATE TABLE agent_departments (
    agent_id VARCHAR2(20) NOT NULL,
    department_id NUMBER NOT NULL,
    CONSTRAINT pk_agent_departments
        PRIMARY KEY (agent_id, department_id),
    CONSTRAINT fk_ad_agent
        FOREIGN KEY (agent_id)
        REFERENCES agents(agent_id),
    CONSTRAINT fk_ad_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
);

CREATE TABLE tickets (
    ticket_id VARCHAR2(20) PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    first_response_at TIMESTAMP,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    reopened_at TIMESTAMP,
    re_resolved_at TIMESTAMP,
    priority VARCHAR2(20) NOT NULL,
    category VARCHAR2(50) NOT NULL,
    department_id NUMBER,
    agent_id VARCHAR2(20),
    status VARCHAR2(30) NOT NULL,
    reopened VARCHAR2(5),
    escalated VARCHAR2(5),

    CONSTRAINT fk_ticket_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id),

    CONSTRAINT fk_ticket_agent
        FOREIGN KEY (agent_id)
        REFERENCES agents(agent_id),

    CONSTRAINT fk_ticket_agent_department
        FOREIGN KEY (agent_id, department_id)
        REFERENCES agent_departments(agent_id, department_id),

    CONSTRAINT chk_ticket_priority
        CHECK (priority IN ('Critical', 'High', 'Medium', 'Low')),

    CONSTRAINT chk_ticket_reopened
        CHECK (reopened IN ('Yes', 'No')),

    CONSTRAINT chk_ticket_escalated
        CHECK (escalated IN ('Yes', 'No'))
);